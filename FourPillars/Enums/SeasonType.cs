    /// 未指定季节
    /// </summary>
    None = 0,

    /// <summary>
    /// 春 - 东方青龙，万物生发
    /// </summary>
    Spring,

    /// <summary>
    /// 夏 - 南方朱雀，万物繁茂
    /// </summary>
    Summer,

    /// <summary>
    /// 季夏（长夏）- 中央勾陈，土德当令
    /// </summary>
    LateSummer,

    /// <summary>
    /// 秋 - 西方白虎，万物肃杀
    /// </summary>
    Autumn,

    /// <summary>
    /// 冬 - 北方玄武，万物闭藏
    /// </summary>
    Winter

}
